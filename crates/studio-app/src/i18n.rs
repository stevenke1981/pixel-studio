//! Bilingual UI strings for Pixel Studio (Traditional Chinese / English).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    ZhTw,
    En,
}

impl Language {
    pub fn name(self) -> &'static str {
        match self {
            Self::ZhTw => "繁體中文",
            Self::En => "English",
        }
    }

    pub fn t(self, key: TextKey) -> &'static str {
        match self {
            Self::ZhTw => key.zh_tw(),
            Self::En => key.en(),
        }
    }
}

